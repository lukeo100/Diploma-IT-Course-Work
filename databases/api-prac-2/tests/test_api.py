"""Tests that run against BOTH versions (see the api fixture in conftest.py).
They follow the test sequences in the two task pages."""
from conftest import send_student

COURSE_NAMES = ["Programming", "Networking", "Cyber Security", "Web Development"]


def test_list_courses(api):
    _, client = api
    response = client.get("/courses")
    assert response.status_code == 200
    courses = response.json()
    assert [c["id"] for c in courses] == [1, 2, 3, 4]  # ordered by id
    assert [c["name"] for c in courses] == COURSE_NAMES


def test_list_students_shows_course_name(api):
    _, client = api
    students = client.get("/students").json()
    assert len(students) == 8
    # The course NAME appears under "course", and course_id is not in the output
    assert students[0] == {"id": 1, "name": "Alice Chen", "course": "Programming"}


def test_get_one_student(api):
    _, client = api
    # The same ids the ORM task asks you to try: 1, 3 and 8
    expected = {1: "Programming", 3: "Networking", 8: "Web Development"}
    for student_id, course in expected.items():
        response = client.get(f"/students/{student_id}")
        assert response.status_code == 200
        assert response.json()["course"] == course


def test_get_missing_student_is_404(api):
    _, client = api
    assert client.get("/students/999").status_code == 404


def test_create_student(api):
    _, client = api
    response = send_student(api, "POST", "/students", "Avery Johnson", 1)
    assert response.status_code == 201
    created = response.json()
    assert created["name"] == "Avery Johnson"
    assert created["course_id"] == 1
    assert created["id"] > 8  # generated by the database, after the 8 seed rows
    # It is really stored: we can read it back
    assert client.get(f"/students/{created['id']}").json()["course"] == "Programming"


def test_update_student(api):
    _, client = api
    student_id = send_student(api, "POST", "/students", "Avery Johnson", 1).json()["id"]

    # Task test: move Avery to course 3 (Cyber Security)
    response = send_student(api, "PUT", f"/students/{student_id}", "Avery Johnson", 3)
    assert response.status_code == 200
    assert response.json()["course_id"] == 3
    assert client.get(f"/students/{student_id}").json()["course"] == "Cyber Security"


def test_update_missing_student_is_404(api):
    _, _ = api
    response = send_student(api, "PUT", "/students/999", "Nobody", 1)
    assert response.status_code == 404


def test_delete_student(api):
    _, client = api
    student_id = send_student(api, "POST", "/students", "Avery Johnson", 1).json()["id"]

    response = client.delete(f"/students/{student_id}")
    assert response.status_code == 200
    assert response.json()["name"] == "Avery Johnson"  # the deleted record is returned

    # Gone from the list, and fetching it now gives 404
    assert "Avery Johnson" not in [s["name"] for s in client.get("/students").json()]
    assert client.get(f"/students/{student_id}").status_code == 404


def test_delete_missing_student_is_404(api):
    _, client = api
    assert client.delete("/students/999").status_code == 404


def test_create_with_unknown_course_is_400(api):
    # The foreign key stops students pointing at a course that does not exist
    response = send_student(api, "POST", "/students", "Ghost", 999)
    assert response.status_code == 400


def test_update_with_unknown_course_is_400(api):
    response = send_student(api, "PUT", "/students/1", "Alice Chen", 999)
    assert response.status_code == 400
